import assert from 'node:assert/strict'
import { readFile, mkdir } from 'node:fs/promises'
import { createRequire } from 'node:module'

const require = createRequire(import.meta.url)
const { chromium } = require(process.env.FLUXLOCK_PLAYWRIGHT || 'playwright-core')
const baseUrl = process.env.FLUXLOCK_TEST_URL || 'http://127.0.0.1:5173'
const resultsPath = process.env.FLUXLOCK_CSV_TEST_RESULTS
assert.ok(resultsPath, 'Set FLUXLOCK_CSV_TEST_RESULTS to the report generated by cargo test csv_market_exports.')
const fixtures = JSON.parse(await readFile(resultsPath, 'utf8'))
const screenshotDir = process.env.FLUXLOCK_SCREENSHOTS
if (screenshotDir) await mkdir(screenshotDir, { recursive: true })

const browser = await chromium.launch({ executablePath: process.env.FLUXLOCK_BROWSER, headless: true })
try {
  for (const fixture of fixtures) {
    for (const width of [375, 1280]) {
      const page = await browser.newPage({ viewport: { width, height: 860 }, colorScheme: 'dark', reducedMotion: 'reduce' })
      const errors = []
      page.on('pageerror', (error) => errors.push(error.message))
      await page.addInitScript(({ fixture, android }) => {
        let imported = false
        window.__csvCalls = []
        if (android) window.AndroidBiometric = { storeKey: () => {}, isAvailable: () => false }
        window.__TAURI_EVENT_PLUGIN_INTERNALS__ = { unregisterListener: () => {} }
        window.__TAURI_INTERNALS__ = {
          transformCallback: () => 1,
          invoke: async (command, args) => {
            switch (command) {
              case 'has_existing_user': return true
              case 'check_login_delay': return 0
              case 'check_biometric': return { available: false, enrolled: false, requires_password: true }
              case 'local_login': return { success: true, token: 'test', user_id: 1, username: 'personne-fictive' }
              case 'check_auto_lock': return { locked: false }
              case 'get_security_status': return { is_readonly: false }
              case 'get_secure_keys': return [
                { id: 1, key_name: 'Clé de test A', key_type: 'encryption', algorithm: 'AES-256-GCM', created_at: '2026-11-19' },
                { id: 2, key_name: 'Clé de test B', key_type: 'encryption', algorithm: 'AES-256-GCM', created_at: '2026-11-19' },
              ]
              case 'get_passwords': return imported ? fixture.passwords : []
              case 'import_passwords_csv': {
                const request = args.request
                if (request.master_password !== ' mot de passe maître fictif ') throw new Error('Le mot de passe maître a été modifié.')
                if (request.csv_content !== fixture.csv.replace(/^\uFEFF/, '')) throw new Error('Le CSV a été modifié.')
                const expectedFormat = fixture.id === 'firefox' ? 'firefox' : 'auto'
                if (request.source_format !== expectedFormat) throw new Error('Format source différent entre aperçu et confirmation.')
                window.__csvCalls.push(request.mode)
                if (request.mode === 'preview') return imported ? fixture.repeated : fixture.preview
                if (request.mode !== 'import' || request.entry_actions.length !== fixture.passwords.length
                    || request.entry_actions.some((action) => action.action !== 'import')) throw new Error('Sélection incorrecte.')
                imported = true
                return fixture.imported
              }
              default: return []
            }
          },
        }
      }, { fixture, android: width < 768 })

      await page.goto(`${baseUrl}/login`)
      await page.getByLabel('Mot de passe maître', { exact: true }).fill(' mot de passe maître fictif ')
      await page.getByRole('button', { name: 'Déverrouiller', exact: true }).click()
      const inventory = page.getByRole('region', { name: 'Contenu du coffre' })
      const keys = inventory.getByRole('link', { name: 'Clés cryptographiques 2' })
      await keys.click()
      await page.getByRole('heading', { name: 'Clés cryptographiques', level: 1 }).waitFor()
      await page.getByText('Clé de test B', { exact: true }).waitFor()
      await page.goBack()
      await inventory.getByRole('link', { name: /Mots de passe/ }).click()

      const openImport = async () => {
        await page.getByRole('button', { name: 'Importer un CSV' }).click()
        const dialog = page.getByRole('dialog', { name: 'Importer des mots de passe' })
        if (fixture.id === 'firefox') await dialog.getByLabel('Format source').selectOption('firefox')
        const [picker] = await Promise.all([
          page.waitForEvent('filechooser'),
          dialog.getByRole('button', { name: 'Choisir un fichier CSV' }).click(),
        ])
        await picker.setFiles({ name: `${fixture.id}-fictif.csv`, mimeType: 'text/csv', buffer: Buffer.from(fixture.csv) })
        await dialog.getByLabel('Mot de passe maître', { exact: true }).fill(' mot de passe maître fictif ')
        await dialog.getByRole('button', { name: 'Analyser le fichier' }).click()
        await dialog.getByText(fixture.label, { exact: true }).waitFor()
        return dialog
      }
      const preview = await openImport()
      for (const password of fixture.passwords) {
        await preview.getByText(password.title, { exact: true }).waitFor()
        await preview.getByText(password.url, { exact: true }).waitFor()
        if (password.category) await preview.getByText(password.category, { exact: true }).waitFor()
        if (password.notes) await preview.getByText(password.notes, { exact: true }).waitFor()
        assert.equal(await preview.getByText(password.password.trim(), { exact: true }).count(), 0)
      }
      assert.equal(await preview.getByText('••••••••', { exact: true }).count(), fixture.passwords.length)
      assert.ok(await page.evaluate(() => document.documentElement.scrollWidth - innerWidth <= 2))
      if (fixture.id === 'brave') {
        const include = preview.getByRole('checkbox', { name: `Inclure ${fixture.passwords[0].title}` })
        await include.uncheck()
        assert.equal(await include.isChecked(), false)
        await include.check()
        await preview.getByText('Lignes ignorées (1)').click()
        await preview.getByText(/Mot de passe vide/).waitFor()
        if (screenshotDir) await page.screenshot({ path: `${screenshotDir}/brave-apercu-${width}.png` })
      }
      await preview.getByRole('button', { name: 'Importer la sélection' }).click()
      await preview.getByText('Import terminé', { exact: true }).waitFor()
      await preview.getByRole('button', { name: 'Fermer', exact: true }).last().click()
      await preview.waitFor({ state: 'hidden' })

      for (const password of fixture.passwords) {
        const row = page.getByRole('listitem').filter({ hasText: password.title })
        await row.getByText(password.title, { exact: true }).waitFor()
        const secret = row.locator('.workspace-secret span').first()
        assert.equal(await secret.textContent(), '••••••••••••')
        await row.getByRole('button', { name: 'Révéler' }).click()
        assert.equal(await secret.textContent(), password.password)
        await row.getByRole('button', { name: 'Masquer' }).click()
        await row.getByRole('button', { name: `Modifier ${password.title}` }).click()
        const edit = page.getByRole('dialog', { name: 'Modifier le mot de passe' })
        assert.equal(await edit.getByLabel('URL').inputValue(), password.url)
        assert.equal(await edit.getByLabel('Notes', { exact: true }).inputValue(), password.notes || '')
        assert.equal(await edit.getByLabel('Catégorie').inputValue(), password.category || '')
        await page.keyboard.press('Escape')
      }
      const repeated = await openImport()
      assert.equal(await repeated.getByRole('radio', { name: 'Ignorer' }).count(), fixture.passwords.length)
      assert.ok(await repeated.getByRole('button', { name: 'Importer la sélection' }).isDisabled())
      assert.deepEqual(await page.evaluate(() => window.__csvCalls), ['preview', 'import', 'preview'])
      assert.deepEqual(errors, [])
      console.log(`${fixture.label} · ${width} px · sélection, aperçu, import, affichage et détection des doublons vérifiés`)
      await page.close()
    }
  }
} finally {
  await browser.close()
}
